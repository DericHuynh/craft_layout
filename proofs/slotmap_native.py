#!/usr/bin/env python3
"""Check the pinned source correspondence and verify SlotMap's owned-arena arithmetic.

The physical-state proof in slotmap.rs supplies the preconditions of these
expressions. Rust's Vec and ManuallyDrop operations form the primitive memory
boundary. The source hashes bind the correspondence to the exact dependency
that cargo test --locked and cargo build --locked use.
"""

import argparse
import hashlib
import json
from pathlib import Path
import re
import shutil
import subprocess
import tempfile
import tomllib


ROOT = Path(__file__).resolve().parents[1]
VERSION = "1.1.1"
CRATE_HASH = "bdd58c3c93c3d278ca835519292445cb4b0d4dc59ccfdf7ceadaab3f8aeb4038"
SOURCE_HASHES = {
    "build.rs": "fa4b3bd978b8f9c9a619b6fd61b4471a9b0a386335dd3b1fc8997daa8a16c4ff",
    "src/basic.rs": "dd4e5c6c87d08086f454b1e062d109582818626f1d8316dcc6a91adb3ed31192",
    "src/lib.rs": "7ccea0d6d7aef7249e823fa6a6b0644f31ef46eefa93d0116ebcae12ff25d22a",
    "src/util.rs": "e21f0622fc4a94b2a6a7efc7ddaa6266914a471ec7eaedc279034bfd24c9a68a",
    "Cargo.toml": "051ed0c65137ce29c8b37ff66d16a9d9190eb1708849e4cc1babcd94b699d764",
}


def pinned_source() -> tuple[str, str]:
    with (ROOT / "Cargo.lock").open("rb") as lock_file:
        packages = tomllib.load(lock_file)["package"]
    locked = [p for p in packages if p["name"] == "slotmap"]
    if len(locked) != 1 or locked[0].get("checksum") != CRATE_HASH:
        raise SystemExit("The SlotMap package in Cargo.lock does not match the audited source.")

    metadata = json.loads(subprocess.check_output(
        ["cargo", "metadata", "--locked", "--format-version", "1"], cwd=ROOT
    ))
    resolved = [p for p in metadata["packages"] if p["name"] == "slotmap"]
    if len(resolved) != 1 or resolved[0]["version"] != VERSION:
        raise SystemExit("Cargo did not resolve the audited SlotMap version.")
    source = Path(resolved[0]["manifest_path"]).parent
    for name, expected in SOURCE_HASHES.items():
        if hashlib.sha256((source / name).read_bytes()).hexdigest() != expected:
            raise SystemExit(f"SlotMap {name} differs from the audited source.")

    basic = (source / "src/basic.rs").read_text()
    keys = (source / "src/lib.rs").read_text()
    if not re.search(
        r"new_key_type!\s*\{\s*pub\(crate\) struct NodeKey;\s*\}",
        (ROOT / "src/layout_tree.rs").read_text(),
    ):
        raise SystemExit("The owned node key is no longer generated by SlotMap.")
    return basic, keys


def extract(source: str, assignment: str) -> str:
    expression, = re.findall(r"^\s*" + re.escape(assignment) + r"\s*(.*);$", source, re.M)
    return expression


def arithmetic_proof(source: str, keys: str) -> str:
    init_body = source.split("pub fn with_capacity_and_key(", 1)[1].split("\n    }", 1)[0]
    reserve_body = source.split("pub fn try_reserve(", 1)[1].split("\n    }", 1)[0]
    insert_body = source.split("pub fn try_insert_with_key<", 1)[1].split("\n    }", 1)[0]
    remove_body = source.split("unsafe fn remove_from_slot(", 1)[1].split("\n    }", 1)[0]
    initialized = extract(init_body, "let mut slots = Vec::with_capacity(").removesuffix(")")
    needed = extract(reserve_body, "let needed =").replace("self.len()", "live").replace("self.slots.len()", "slots")
    generation = extract(insert_body, "let occupied_version =").replace("slot.version", "version")
    free_head = "index " + extract(insert_body, "self.free_head = kd.idx")
    removed = extract(remove_body, "slot.version =").replace("slot.version", "version")
    occupied_body = source.split("pub fn occupied(&self) -> bool {", 1)[1].split("\n    }", 1)[0]
    occupied = occupied_body.strip().replace("self.version", "version")
    lookup_guards = set()
    for signature in ("pub fn contains_key(&self, key: K)", "pub fn get(&self, key: K)", "pub fn get_mut(&mut self, key: K)"):
        body = source.split(signature, 1)[1].split("\n    }", 1)[0]
        guard, = re.findall(r"\|slot\| ([^\n]+)\)\s*$", body.split(".map(|", 1)[0], re.M)
        lookup_guards.add(guard)
    if len(lookup_guards) != 1:
        raise SystemExit("SlotMap's checked lookup predicates differ.")
    lookup_guard = lookup_guards.pop().replace("slot.version", "version").replace("kd.version.get()", "key_version")
    full, = re.findall(r"^\s*if (self\.slots\.len\(\) >= .+) \{$", insert_body, re.M)
    full = full.replace("self.slots.len()", "slots")
    key_body = keys.split("impl KeyData {", 1)[1].split("\n    fn null()", 1)[0]
    nonzero, = re.findall(r"NonZeroU32::new_unchecked\((.*)\)", key_body)
    positive, = re.findall(r"debug_assert!\((.*)\);", key_body)
    # The two increment statements in try_insert_with_key are identical.
    increment = re.findall(r"^\s*self\.num_elems \+= (.*);$", insert_body, re.M)
    if len(increment) != 2 or increment[0] != increment[1]:
        raise SystemExit("SlotMap's live-count updates no longer match.")
    decrement = extract(remove_body, "self.num_elems -=")

    return f"""
use vstd::prelude::*;

verus! {{

fn initial_capacity(capacity: usize) -> (physical: usize)
    requires capacity < u32::MAX,
    ensures physical == capacity + 1,
    no_unwind
{{
    {initialized}
}}

fn reserve(live: usize, additional: usize, slots: usize) -> (required: usize)
    requires slots > 0, live + additional < u32::MAX,
    ensures required == vstd::math::max(0, live + additional - (slots - 1)),
    no_unwind
{{
    {needed}
}}

fn reuse_version(version: u32) -> (key_version: u32)
    ensures key_version == (version | 1), key_version & 1 == 1, key_version > 0,
    no_unwind
{{
    assert((version | 1) & 1 == 1 && (version | 1) > 0) by(bit_vector);
    {generation}
}}

fn full_on_append(slots: usize) -> (full: bool)
    requires slots < u32::MAX,
    ensures !full,
    no_unwind
{{
    {full}
}}

fn key_version(version: u32) -> (encoded: u32)
    requires version > 0,
    ensures encoded > 0, encoded & 1 == 1,
        version & 1 == 1 ==> encoded == version,
    no_unwind
{{
    assert({positive});
    assert(({nonzero}) > 0 && ({nonzero}) & 1 == 1
        && (version & 1 == 1 ==> ({nonzero}) == version)) by(bit_vector);
    {nonzero}
}}

fn lookup_matches(version: u32, key_version: u32) -> (matched: bool)
    requires key_version & 1 == 1,
    ensures matched == (version == key_version),
        matched ==> {occupied},
    no_unwind
{{
    if {lookup_guard} {{
        assert({occupied}) by(bit_vector)
            requires {lookup_guard}, key_version & 1 == 1;
    }}
    {lookup_guard}
}}

fn appended_head(index: u32) -> (head: u32)
    requires index < u32::MAX,
    ensures head == index + 1,
    no_unwind
{{
    {free_head}
}}

fn freed_version(version: u32) -> (vacant_version: u32)
    requires version & 1 == 1,
    ensures vacant_version == version.wrapping_add(1), vacant_version & 1 == 0,
    no_unwind
{{
    assert(version.wrapping_add(1) & 1 == 0) by(bit_vector) requires version & 1 == 1;
    {removed}
}}

fn added(live: u32) -> (next: u32)
    requires live + 1 < u32::MAX,
    ensures next == live + 1,
    no_unwind
{{
    live + {increment[0]}
}}

fn removed(live: u32) -> (next: u32)
    requires live > 0,
    ensures next == live - 1,
    no_unwind
{{
    live - {decrement}
}}

}}
"""


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--verus", default="verus", help="Path to the Verus executable")
    args = parser.parse_args()
    executable = shutil.which(args.verus)
    if executable is None:
        raise SystemExit(f"Verus executable not found: {args.verus}")
    executable = str(Path(executable).resolve())
    basic, keys = pinned_source()
    with tempfile.TemporaryDirectory(prefix="craft-layout-slotmap-") as temp:
        kernel = Path(temp) / "slotmap_arithmetic.rs"
        kernel.write_text(arithmetic_proof(basic, keys))
        for proof in [ROOT / "proofs/slotmap.rs", kernel]:
            subprocess.run(
                [executable, "--no-cheating", "--crate-type", "lib", str(proof)],
                cwd=temp,
                check=True,
            )


if __name__ == "__main__":
    main()
